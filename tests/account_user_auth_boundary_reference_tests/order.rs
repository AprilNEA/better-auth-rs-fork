const COOKIE_FAILURE: &str =
    "Cookies Max-Age SHOULD NOT be greater than 400 days (34560000 seconds) in duration.";

async fn contract<S: AuthSchema>(
    raw: Arc<dyn AuthStore<S>>,
    database: Option<&DatabaseConnection>,
    scenario: &Scenario,
    case: &Case,
) -> TestResult {
    storage::seed(raw.as_ref(), scenario).await?;
    let before = storage::snapshot(raw.as_ref(), database, &[]).await?;
    storage::assert_snapshot(&before, &case.before, database.is_some(), case);
    let events = Events::default();
    let mut options = config::configured(scenario, case.joins, Some(&events))?;
    options.account.encrypt_oauth_tokens = Some(true);
    options.account.store_account_cookie = Some(true);
    options.account.update_account_on_sign_in = Some(scenario.mode != "update-disabled");
    options.advanced.database.generate_id = Some(better_auth_core::id::IdGeneration::Custom(
        better_auth_core::id::IdGenerator::new(|request| {
            Ok(Some(format!("zz-order-{}", request.model)))
        }),
    ));
    if scenario.mode == "cookie-failure" {
        let _ = options
            .advanced
            .cookies
            .get_or_insert_with(Default::default)
            .insert(
                "account_data".into(),
                better_auth_core::CookieOverride {
                    attributes: better_auth_core::CookieAttributes {
                        max_age: Some(34_560_001.0),
                        ..Default::default()
                    },
                    ..Default::default()
                },
            );
    }
    let hooks = Arc::new(hooks::Hooks::new(events.clone(), scenario)?);
    let store = raw.with_runtime(
        Arc::new(options.clone()),
        vec![hooks.clone()],
        Default::default(),
    )?;
    let harness =
        http::auth_with_after(store, options, scenario, &events, None, Some(hooks)).await?;
    let request = match (&harness.flow, &case.setup) {
        (Some(flow), Some(setup)) => {
            let request = events
                .capture(flow.prepare(harness.auth.clone(), setup, &case.request))
                .await?;
            assert!(events.take()?.is_empty());
            assert_eq!(
                storage::snapshot(raw.as_ref(), database, &[]).await?,
                before
            );
            request
        }
        (None, None) => case.request.clone(),
        _ => return Err("OAuth order setup must match the callback scenario".into()),
    };
    let start = chrono::Utc::now().timestamp_millis();
    let mut response = events
        .capture(http::request(harness.auth, &request))
        .await?;
    let end = chrono::Utc::now().timestamp_millis();
    let mut actual = events.take()?;
    if let Some(flow) = &harness.flow {
        flow.verify_and_normalize(&mut actual)?;
    }
    let tokens = super::observe::issued_tokens(&actual)?;
    let mut after = storage::snapshot(raw.as_ref(), database, &tokens).await?;
    let anchors =
        observe::Anchors::verify(&actual, &before, &after, &response, scenario, start..=end)?;
    let observations = anchors.account_cookies.clone();
    anchors.normalize_events(&mut actual, scenario)?;
    anchors.normalize_storage(&mut after)?;
    anchors.normalize_response(&mut response)?;
    observe::assert_events(&actual, case, scenario)?;
    storage::assert_snapshot(&after, &case.after, database.is_some(), case);
    assert_eq!(response.status, case.response.status, "{case:?}");
    assert_eq!(response.headers, case.response.headers, "{case:?}");
    assert_eq!(response.cookies, case.response.cookies, "{case:?}");
    if response.body.is_empty() {
        assert_eq!(response.body, case.response.body);
    } else {
        assert_eq!(
            serde_json::from_str::<Value>(&response.body)?,
            serde_json::from_str::<Value>(&case.response.body)?,
            "{case:?}"
        );
    }
    assert_eq!(
        Some(json!({"accountCookies": observations})),
        case.observations
    );
    assert_eq!(
        case.checked,
        json!({
            "noNetwork": true, "completeStorage": true, "completeHookKeys": true,
            "encryptedTokenVerified": anchors.encrypted_token,
            "accountCookieVerified": !observations.is_empty(),
            "sessionCookieMatchesStoredToken": anchors.token.is_some(),
            "oauthStateAndCodeVerifierVerified": scenario.callback,
        })
    );
    Ok(())
}

#[tokio::test]
#[ignore = "Requires the fresh Better Auth 1.7.6 fixture generated by the paired CI stage"]
async fn oauth_signin_order_matches_upstream_http() -> TestResult {
    let fixture = Fixture::read_order()?;
    for case in &fixture.cases {
        let scenario = fixture.scenario(&case.scenario)?;
        match case.backend.as_str() {
            "memory" => {
                contract(
                    Arc::new(EphemeralStore::new(Arc::new(config::baseline()))),
                    None,
                    scenario,
                    case,
                )
                .await?
            }
            "sqlite" => {
                let database = storage::sqlite(scenario).await?;
                contract(
                    Arc::new(SeaOrmStore::<models::Core>::new(
                        config::baseline(),
                        database.clone(),
                    )),
                    Some(&database),
                    scenario,
                    case,
                )
                .await?;
            }
            backend => return Err(format!("Unexpected OAuth order backend: {backend}").into()),
        }
    }
    Ok(())
}
